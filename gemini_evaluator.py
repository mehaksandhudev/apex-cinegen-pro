"""
Dynamic Gemini AI Evaluator & Viral Topic Strategist
Features:
1. Real Gemini LLM API evaluation (dynamic, intelligent, context-aware).
2. No rigid or hardcoded keyword lists.
3. Memory tracking (used_topics.json) so previously generated stories are never repeated.
4. If ideas are weak, repetitive, or unoriginal, Gemini dynamically authors customized,
   creative feedback to push ChatGPT in exciting new directions.
5. Selects the single best topic based on genuine viral retention, humor, and spectacle.
"""

import os
import json
import requests
from pathlib import Path

BASE_DIR = Path(__file__).parent.resolve()
HISTORY_FILE = BASE_DIR / "used_topics.json"

def load_used_topics() -> list[str]:
    """Loads previously used topic titles from disk."""
    if HISTORY_FILE.exists():
        try:
            with open(HISTORY_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return []
    return []

def save_used_topic(title: str):
    """Saves a selected topic title so it won't be repeated in future runs."""
    topics = load_used_topics()
    clean = title.strip()
    if clean and clean not in topics:
        topics.append(clean)
        with open(HISTORY_FILE, "w", encoding="utf-8") as f:
            json.dump(topics, f, indent=2, ensure_ascii=False)
        print(f"  [Memory] Recorded winning topic to used_topics.json: '{clean}'")

def call_gemini_api(prompt: str, api_key: str) -> str:
    """Calls Gemini 2.5 Flash API with quota-efficient settings."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={api_key}"
    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "temperature": 0.7,
            "maxOutputTokens": 2048
        }
    }
    headers = {"Content-Type": "application/json"}
    resp = requests.post(url, json=payload, headers=headers, timeout=25)
    if resp.status_code == 200:
        data = resp.json()
        return data["candidates"][0]["content"]["parts"][0]["text"].strip()
    raise RuntimeError(f"Gemini API error {resp.status_code}: {resp.text}")

def evaluate_and_pick_topic(ideas_text: str, api_key: str = None, num_clips: int = 2) -> tuple[str, str, str]:
    """
    Evaluates ChatGPT's 10 candidate ideas dynamically.
    Returns: (decision_type, content, reason)
    - If ideas should be rerolled: ("REROLL", dynamic_reroll_prompt_from_gemini, reason)
    - If a winning idea is picked:  ("WINNER", topic_number_str, title_and_reason)
    """
    used_topics = load_used_topics()
    used_summary = "\n".join([f"- {t}" for t in used_topics[-15:]]) if used_topics else "None (first run)"

    if num_clips == 3:
        format_guidance = (
            "FORMAT TARGET: **30-SECOND 3-CLIP EPIC STORY** (Clip 1: Hook & Rival Taunt -> "
            "Clip 2: Sheru's Viral Power Flex -> Clip 3: Grand Crowd Payoff & Mic-Drop). "
            "Pick the idea with the strongest 3-act escalation, biggest visual spectacle, and funniest payoff."
        )
    else:
        format_guidance = (
            "FORMAT TARGET: **20-SECOND 2-CLIP PUNCHY STORY** (Clip 1: Concept & Taunt -> "
            "Clip 2: Instant Delivery & Mic-Drop). Pick the tightest, fastest-hitting, funniest idea."
        )
    
    eval_prompt = f"""You are a world-class viral YouTube Shorts and Instagram Reels creative director.
You are evaluating 10 video ideas for an Indian comedy short featuring "Sheru Bhai" (a billionaire anthropomorphic lion in a white suit, funny animal rivals, rapid Hindi dialogue, absurd luxury flexes, and motivational comeback stories).

{format_guidance}

PREVIOUSLY USED TOPICS (Do NOT repeat these themes):
{used_summary}

HERE ARE THE 10 CANDIDATE IDEAS GENERATED BY CHATGPT:
{ideas_text}

CRITICAL INSTRUCTIONS:
- Score the candidate ideas based on genuine originality, humor, and viral retention.
- Do NOT spoon-feed or suggest specific items/scenarios (never say "like this" or "like that"). Let ChatGPT invent on its own.
- If the batch is uninspired, repetitive, or low-energy, output:
REROLL: [A clean, direct message telling ChatGPT that these ideas are not unique or exciting enough, and asking it to generate 10 completely new, higher-energy, and more creative story ideas about Sheru Bhai.]

- If there is a strong, unique, and high-viral idea (not repeating past topics), select the #1 best one:
WINNER: [Topic number from 1 to 10]
TITLE: [Exact title of the winning idea]
REASON: [1 sentence explaining why this specific idea will hold viewer retention and drive high engagement.]
"""

    print("\n" + "="*60)
    print("  [Gemini AI Strategist] Dynamically auditing ideas...")
    print("="*60)
    
    gemini_response = ""
    if api_key and api_key.strip():
        try:
            gemini_response = call_gemini_api(eval_prompt, api_key.strip())
        except Exception as e:
            print(f"  [API Warning] Gemini API call failed: {e}")
            
    if not gemini_response:
        # Fallback only if no API key is provided
        gemini_response = dynamic_fallback_selector(ideas_text, used_topics)
        
    print("\n[Gemini AI Strategist Assessment]:")
    print(gemini_response)
    print("="*60 + "\n")
    
    # Clean markdown formatting for clean parsing
    clean_resp = gemini_response.replace("**", "")
    
    # Parse decision
    if "REROLL:" in clean_resp:
        reroll_instruction = clean_resp.split("REROLL:")[1].strip()
        return ("REROLL", reroll_instruction, "Ideas needed more originality or higher viral energy.")
        
    elif "WINNER:" in clean_resp:
        lines = clean_resp.splitlines()
        winner_num = "1"
        title = ""
        reason = ""
        for line in lines:
            if "WINNER:" in line:
                winner_num = "".join([c for c in line.split("WINNER:")[1] if c.isdigit()]) or "1"
            elif "TITLE:" in line:
                title = line.split("TITLE:")[1].strip()
            elif "REASON:" in line:
                reason = line.split("REASON:")[1].strip()
                
        if not title:
            title = f"Topic #{winner_num}"
            
        save_used_topic(title)
        return ("WINNER", winner_num, f"{title} ({reason})")
        
    return ("WINNER", "1", "Selected top candidate")

def dynamic_fallback_selector(ideas_text: str, used_topics: list[str]) -> str:
    """Fallback selector when no Gemini API key is configured. Selects the freshest candidate without forcing static keywords."""
    lines = [l.strip() for l in ideas_text.splitlines() if l.strip()]
    topic_lines = []
    for l in lines:
        if any(l.startswith(f"{i}.") or l.startswith(f"**{i}.") or l.startswith(f"Idea {i}") for i in range(1, 11)):
            topic_lines.append(l)
            
    if not topic_lines:
        topic_lines = lines[:10]

    # Pick the first one that doesn't significantly overlap with previous runs
    for i, t in enumerate(topic_lines, 1):
        is_repetitive = False
        for u in used_topics:
            words_u = set([w.lower() for w in u.split() if len(w) > 3])
            words_t = set([w.lower() for w in t.split() if len(w) > 3])
            if len(words_u.intersection(words_t)) >= 3:
                is_repetitive = True
                break
        if not is_repetitive:
            return f"WINNER: {i}\nTITLE: {t}\nREASON: Fresh concept with zero overlap with past runs."

    return f"WINNER: 1\nTITLE: {topic_lines[0]}\nREASON: Selected top topic."

